import re  # noqa: E402  (placed after helpers to avoid shadowing builtins)


class ReportAgent:
    """
    Generates Markdown and PDF research reports.

    Usage:
        agent = ReportAgent()
        result = agent.generate(synthesis, citation, session_id="abc123")
        print(result.md_path)
    """

    def __init__(self, reports_dir: Optional[Path] = None) -> None:
        """
        Args:
            reports_dir: Directory to save reports.  Defaults to
                         ``settings.reports_dir``.
        """
        self._reports_dir = reports_dir or settings.reports_dir
        ensure_dir(Path(self._reports_dir))
        logger.info("ReportAgent ready (output_dir=%s).", self._reports_dir)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def generate(
        self,
        synthesis: SynthesisResult,
        citation: CitationResult,
        session_id: str = "",
        save_markdown: bool = True,
        save_pdf: bool = True,
    ) -> ReportResult:
        """
        Generate a research report from synthesis and citation results.

        Args:
            synthesis:      ``SynthesisResult`` from Module 6.
            citation:       ``CitationResult`` from Module 7.
            session_id:     Optional session identifier for metadata.
            save_markdown:  If True, save ``.md`` file to ``reports_dir``.
            save_pdf:       If True, save ``.pdf`` file to ``reports_dir``.

        Returns:
            A ``ReportResult`` with content and optional file paths.
        """
        # ── Build Markdown content ────────────────────────────────────────
        md_content = build_markdown_report(synthesis, citation, session_id)
        now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        word_count = len(synthesis.answer.split())

        # ── Generate output filename ──────────────────────────────────────
        timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        safe_q = sanitise_filename(synthesis.question[:60])
        base_name = f"scipilot_{timestamp}_{safe_q}"

        md_path: Optional[Path] = None
        pdf_path: Optional[Path] = None

        # ── Save Markdown ─────────────────────────────────────────────────
        if save_markdown:
            md_path = Path(self._reports_dir) / f"{base_name}.md"
            md_path.write_text(md_content, encoding="utf-8")
            logger.info(
                "Markdown report saved: %s (%s)",
                md_path.name,
                format_file_size(md_path.stat().st_size),
            )

        # ── Save PDF ──────────────────────────────────────────────────────
        if save_pdf:
            pdf_path = Path(self._reports_dir) / f"{base_name}.pdf"
            try:
                build_pdf_report(md_content, pdf_path)
                logger.info(
                    "PDF report saved: %s (%s)",
                    pdf_path.name,
                    format_file_size(pdf_path.stat().st_size),
                )
            except Exception as exc:  # noqa: BLE001
                logger.error("PDF generation failed: %s", exc)
                pdf_path = None

        return ReportResult(
            md_content=md_content,
            generated_at=now_str,
            question=synthesis.question,
            word_count=word_count,
            md_path=md_path,
            pdf_path=pdf_path,
            metadata={
                "session_id": session_id,
                "citation_style": citation.style.value,
                "model_id": synthesis.model_id,
                "num_citations": len(citation.citations),
                "num_context_chunks": len(synthesis.context_chunks),
            },
        )

    def generate_markdown_only(
        self,
        synthesis: SynthesisResult,
        citation: CitationResult,
        session_id: str = "",
    ) -> str:
        """
        Return only the Markdown string without saving any files.

        Useful for the Streamlit dashboard preview.

        Args:
            synthesis: ``SynthesisResult`` from Module 6.
            citation:  ``CitationResult`` from Module 7.
            session_id: Optional session ID.

        Returns:
            Markdown report string.
        """
        return build_markdown_report(synthesis, citation, session_id)
