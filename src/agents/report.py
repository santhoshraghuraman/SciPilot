"""
SciPilot — Report Generator  (src/agents/report.py)
=====================================================
Produces Markdown and PDF research reports from a ``SynthesisResult``
and a ``CitationResult``.

Report structure:
  # SciPilot Research Report
  **Question:** …
  **Generated:** YYYY-MM-DD HH:MM:SS
  ---
  ## Answer
  <grounded answer with inline citations>
  ---
  ## Sources Used
  | # | Title | Source | Page |
  …
  ---
  ## References
  <APA / IEEE formatted citations>
  ---
  ## Report Metadata
  | Key | Value |
  …

Design:
  - Markdown is written first; the PDF is rendered from the same content.
  - ``fpdf2`` is used for PDF generation — pure Python, no system dependencies.
  - Filenames are sanitised and timestamped so reports never overwrite each other.
  - The module is pure (no IBM API calls) — all content is pre-generated by
    earlier modules.

Dependencies:
  - fpdf2     (``pip install fpdf2``)
  - markdown  (``pip install markdown``)
  - src.agents.synthesis (SynthesisResult)
  - src.agents.citation  (CitationResult)
  - src.utils.config     (settings)
  - src.utils.helpers    (sanitise_filename, ensure_dir, format_file_size)
  - src.utils.logger     (get_logger)
"""

from __future__ import annotations

import datetime
import textwrap
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional

from src.agents.citation import CitationResult
from src.agents.synthesis import SynthesisResult
from src.utils.config import settings
from src.utils.helpers import ensure_dir, format_file_size, sanitise_filename
from src.utils.logger import get_logger

logger = get_logger(__name__)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_APP_NAME = "SciPilot"
_APP_SUBTITLE = "AI Research Assistant — Powered by IBM watsonx.ai & Llama 3.3 70B"
_PDF_FONT = "Helvetica"         # built-in fpdf2 font, no external file needed
_PDF_PAGE_W = 210               # A4 width mm
_PDF_MARGIN = 15                # mm
_PDF_LINE_H = 6                 # mm per line


# ---------------------------------------------------------------------------
# Data model
# ---------------------------------------------------------------------------

@dataclass
class ReportResult:
    """
    Output of ``ReportAgent.generate()``.

    Attributes:
        md_path:   Path to the saved Markdown file (or None if not saved).
        pdf_path:  Path to the saved PDF file (or None if not saved).
        md_content: The Markdown string (always populated).
        generated_at: ISO timestamp of report generation.
        question:  The research question the report answers.
        word_count: Approximate word count of the answer section.
        metadata:  Additional key-value pairs.
    """

    md_content: str
    generated_at: str
    question: str
    word_count: int
    md_path: Optional[Path] = None
    pdf_path: Optional[Path] = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    @property
    def has_markdown(self) -> bool:
        return self.md_path is not None and self.md_path.exists()

    @property
    def has_pdf(self) -> bool:
        return self.pdf_path is not None and self.pdf_path.exists()

    def __repr__(self) -> str:
        return (
            f"ReportResult(question={self.question[:40]!r}, "
            f"words={self.word_count}, "
            f"md={self.has_markdown}, pdf={self.has_pdf})"
        )


# ---------------------------------------------------------------------------
# Markdown builder
# ---------------------------------------------------------------------------

def build_markdown_report(
    synthesis: SynthesisResult,
    citation: CitationResult,
    session_id: str = "",
) -> str:
    """
    Build the full Markdown report string from synthesis and citation results.

    Args:
        synthesis:  ``SynthesisResult`` from Module 6.
        citation:   ``CitationResult`` from Module 7.
        session_id: Optional session identifier for the metadata section.

    Returns:
        Multi-line Markdown string.
    """
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines: List[str] = []

    # ── Header ───────────────────────────────────────────────────────────
    lines += [
        f"# {_APP_NAME} Research Report",
        f"*{_APP_SUBTITLE}*",
        "",
        f"**Question:** {synthesis.question}",
        f"**Generated:** {now}",
        f"**Citation Style:** {citation.style.value}",
        "",
        "---",
        "",
    ]

    # ── Answer section ────────────────────────────────────────────────────
    lines += [
        "## Answer",
        "",
        synthesis.answer if synthesis.answer else "_No answer generated._",
        "",
        "---",
        "",
    ]

    # ── Sources Used table ─────────────────────────────────────────────────
    lines += [
        "## Sources Used",
        "",
        "| # | Title | File | Page | Score |",
        "|---|-------|------|------|-------|",
    ]

    for i, chunk in enumerate(synthesis.context_chunks, start=1):
        score = (
            f"{synthesis.metadata.get('scores', [None] * (i + 1))[i - 1]:.3f}"
            if "scores" in synthesis.metadata
            else "N/A"
        )
        title = (chunk.doc_title or chunk.source)[:50]
        lines.append(
            f"| {i} | {title} | `{chunk.source}` | {chunk.page_number} | {score} |"
        )

    lines += ["", "---", ""]

    # ── References section ─────────────────────────────────────────────────
    if not citation.is_empty:
        lines += [citation.references_block, "---", ""]
    else:
        lines += ["## References", "", "_No citations generated._", "", "---", ""]

    # ── Metadata section ──────────────────────────────────────────────────
    lines += [
        "## Report Metadata",
        "",
        "| Field | Value |",
        "|-------|-------|",
        f"| Model | `{synthesis.model_id}` |",
        f"| Input Tokens | {synthesis.input_tokens} |",
        f"| Output Tokens | {synthesis.output_tokens} |",
        f"| Latency | {synthesis.latency_s:.2f}s |",
        f"| Grounded | {'Yes' if synthesis.is_grounded else 'No'} |",
        f"| Citations | {len(citation.citations)} |",
        f"| Context Chunks | {len(synthesis.context_chunks)} |",
    ]

    if session_id:
        lines.append(f"| Session ID | `{session_id}` |")

    lines += [
        "",
        "---",
        "",
        f"*Report generated by {_APP_NAME} — IBM SkillsBuild × AICTE 2026*",
        "",
    ]

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# PDF builder
# ---------------------------------------------------------------------------

def build_pdf_report(
    md_content: str,
    output_path: Path,
) -> Path:
    """
    Convert a Markdown report string to a PDF file using ``fpdf2``.

    The conversion is intentionally simple — we render the Markdown as
    styled plain text rather than full HTML conversion, keeping the
    dependency footprint minimal (no BeautifulSoup, no headless browser).

    Rendering rules:
      - Lines starting with ``# `` → large bold heading
      - Lines starting with ``## `` → medium bold heading
      - Lines starting with ``### `` → small bold heading
      - Lines starting with ``| `` → monospace table row
      - Lines starting with ``---`` → horizontal rule
      - Lines starting with ``*`` or ``_`` (italic wrappers) → italic text
      - All other lines → normal body text

    Args:
        md_content:  Full Markdown string from ``build_markdown_report``.
        output_path: Destination ``.pdf`` file path.

    Returns:
        The ``output_path``, for method chaining.

    Raises:
        ImportError: If ``fpdf2`` is not installed.
    """
    try:
        from fpdf import FPDF, XPos, YPos
    except ImportError as exc:
        raise ImportError(
            "fpdf2 is not installed. Run: pip install fpdf2"
        ) from exc

    pdf = FPDF(orientation="P", unit="mm", format="A4")
    pdf.set_margins(_PDF_MARGIN, _PDF_MARGIN, _PDF_MARGIN)
    pdf.set_auto_page_break(auto=True, margin=_PDF_MARGIN)
    pdf.add_page()

    usable_w = _PDF_PAGE_W - 2 * _PDF_MARGIN

    def _safe(text: str) -> str:
        """Replace characters unsupported by Latin-1 Helvetica font."""
        return text.encode("latin-1", errors="replace").decode("latin-1")

    def _mcell(w: float, h: float, txt: str, **kw) -> None:
        """multi_cell wrapper using non-deprecated XPos/YPos API."""
        pdf.multi_cell(w, h, _safe(txt),
                       new_x=XPos.LMARGIN, new_y=YPos.NEXT, **kw)

    for raw_line in md_content.splitlines():
        line = raw_line.rstrip()

        # ── Headings ─────────────────────────────────────────────────────
        if line.startswith("# ") and not line.startswith("## "):
            pdf.set_font(_PDF_FONT, "B", 16)
            _mcell(usable_w, 8, line[2:])
            pdf.ln(2)

        elif line.startswith("## "):
            pdf.set_font(_PDF_FONT, "B", 13)
            _mcell(usable_w, 7, line[3:])
            pdf.ln(1)

        elif line.startswith("### "):
            pdf.set_font(_PDF_FONT, "B", 11)
            _mcell(usable_w, 6, line[4:])

        # ── Horizontal rule ───────────────────────────────────────────────
        elif line.startswith("---"):
            pdf.set_draw_color(180, 180, 180)
            pdf.line(
                _PDF_MARGIN,
                pdf.get_y(),
                _PDF_PAGE_W - _PDF_MARGIN,
                pdf.get_y(),
            )
            pdf.ln(3)

        # ── Table rows ────────────────────────────────────────────────────
        elif line.startswith("|"):
            # Skip separator rows (|---|---|)
            if re.match(r"^\|[\s\-|:]+\|$", line):
                continue
            cells = [c.strip() for c in line.strip("|").split("|")]
            cell_w = usable_w / max(len(cells), 1)
            pdf.set_font("Courier", "", 8)
            for cell in cells:
                truncated = cell[:30] + ">" if len(cell) > 31 else cell
                pdf.cell(cell_w, _PDF_LINE_H - 1, _safe(truncated), border=0)
            pdf.ln(_PDF_LINE_H - 1)

        # ── Blank line ────────────────────────────────────────────────────
        elif not line.strip():
            pdf.ln(2)

        # ── Body / italic lines ───────────────────────────────────────────
        else:
            clean = line.lstrip("*_`").rstrip("*_`")
            if line.startswith("*") or line.startswith("_"):
                pdf.set_font(_PDF_FONT, "I", 10)
            else:
                pdf.set_font(_PDF_FONT, "", 10)

            wrapped = textwrap.wrap(clean, width=90) or [""]
            for wline in wrapped:
                _mcell(usable_w, _PDF_LINE_H, wline)

    ensure_dir(output_path.parent)
    pdf.output(str(output_path))
    return output_path


