"""
SciPilot — Top-Level Agent Orchestrator
=========================================
Wires all SciPilot agents into a single end-to-end research pipeline.

Pipeline (triggered by ``Orchestrator.run()``):
  1. PlannerAgent    → decompose question into sub-questions
  2. RetrieverAgent  → semantic search (FAISS + IBM embeddings) per sub-question
  3. SynthesisAgent  → IBM Granite grounded answer
  4. VerificationAgent → confidence score + verdict
  5. CitationAgent   → APA / IEEE formatted references
  6. ReportAgent     → Markdown + PDF report
  7. MemoryAgent     → persist session to IBM COS (or local)

Each agent is lazily imported on first ``run()`` call so the application
starts instantly even if some optional SDK dependencies are missing.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from src.utils.config import settings
from src.utils.logger import get_logger

logger = get_logger(__name__)


# ---------------------------------------------------------------------------
# Data Transfer Objects
# ---------------------------------------------------------------------------

@dataclass
class ResearchRequest:
    """
    Encapsulates everything the user submits for a research query.

    Attributes:
        question:        The raw research question.
        session_id:      Unique identifier for this session (UUID string).
        paper_ids:       Optional list of specific paper doc_hashes to restrict search.
        citation_style:  "APA" or "IEEE".
        generate_report: Whether to produce a full PDF/MD report.
        top_k:           Override the default retrieval top-k.
    """
    question: str
    session_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    paper_ids: Optional[List[str]] = None
    citation_style: str = "APA"
    generate_report: bool = True
    top_k: Optional[int] = None


@dataclass
class ResearchResponse:
    """
    The fully assembled output returned to the UI.

    Attributes:
        answer:         Grounded answer from IBM Granite.
        sub_questions:  Sub-questions generated by the Planner.
        sources:        Retrieved source chunks with metadata dicts.
        citations:      Formatted citation strings.
        confidence:     Overall confidence score [0.0–1.0].
        verdict:        "HIGH" / "MEDIUM" / "LOW".
        report_md_path: Path to the Markdown report (if generated).
        report_pdf_path: Path to the PDF report (if generated).
        session_id:     Echo of the request session ID.
        metadata:       Timing, token counts, etc.
    """
    answer: str
    sub_questions: List[str] = field(default_factory=list)
    sources: List[Dict[str, Any]] = field(default_factory=list)
    citations: List[str] = field(default_factory=list)
    confidence: float = 0.0
    verdict: str = "LOW"
    report_md_path: Optional[str] = None
    report_pdf_path: Optional[str] = None
    session_id: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)


# ---------------------------------------------------------------------------
# Orchestrator
# ---------------------------------------------------------------------------

class Orchestrator:
    """
    Wires all SciPilot agents into a single end-to-end research pipeline.

    Each agent is lazily loaded on first use to keep startup time minimal.

    Usage:
        from src.orchestrator import Orchestrator, ResearchRequest
        orc = Orchestrator()
        orc.load_vector_store()          # call once at app startup
        response = orc.run(ResearchRequest(question="What is attention?"))
    """

    def __init__(self) -> None:
        logger.info(
            "Initialising SciPilot Orchestrator v%s", settings.app_version
        )
        settings.ensure_directories()
        self._agents_ready = False
        self._vector_store = None   # populated by load_vector_store()

    # ------------------------------------------------------------------
    # Startup
    # ------------------------------------------------------------------

    def load_vector_store(self, base_path=None):
        """
        Load (or create) the FAISS vector store.  Call once at app startup.

        Args:
            base_path: Override the default index path from settings.
        """
        from src.rag.vector_store import VectorStore
        self._vector_store = VectorStore.load_or_create(base_path)
        logger.info(
            "VectorStore ready: %d chunk(s) indexed.", self._vector_store.size
        )

    def _load_agents(self) -> None:
        """Lazily import and initialise all agents on first run()."""
        if self._agents_ready:
            return

        logger.info("Loading SciPilot agents …")

        from src.agents.citation import CitationAgent, CitationStyle
        from src.agents.memory import MemoryAgent
        from src.agents.planner import PlannerAgent
        from src.agents.report import ReportAgent
        from src.agents.retriever import RetrieverAgent
        from src.agents.synthesis import SynthesisAgent
        from src.agents.verification import VerificationAgent

        if self._vector_store is None:
            self.load_vector_store()

        self._planner    = PlannerAgent()
        self._retriever  = RetrieverAgent(self._vector_store)
        self._synthesiser = SynthesisAgent()
        self._verifier   = VerificationAgent()
        self._citer      = CitationAgent()
        self._reporter   = ReportAgent()
        self._memory     = MemoryAgent()

        self._agents_ready = True
        logger.info("All agents loaded and ready.")

    # ------------------------------------------------------------------
    # Main pipeline
    # ------------------------------------------------------------------

    def run(self, request: ResearchRequest) -> ResearchResponse:
        """
        Execute the full agentic research pipeline.

        Args:
            request: A ``ResearchRequest`` from the UI layer.

        Returns:
            A fully populated ``ResearchResponse``.
        """
        self._load_agents()

        logger.info(
            "[%s] Research pipeline start: %s",
            request.session_id[:8],
            request.question[:80],
        )

        # ── Step 1: Plan ─────────────────────────────────────────────────
        plan = self._planner.plan(request.question)
        sub_questions = plan.sub_questions
        logger.info("Plan: %d sub-question(s).", len(sub_questions))

        # ── Step 2: Retrieve — one pass per sub-question, merge results ───
        from src.rag.chunk import TextChunk
        all_chunks: List[TextChunk] = []
        seen_hashes = set()
        for sq in sub_questions:
            try:
                retrieval = self._retriever.retrieve(
                    sq,
                    top_k=request.top_k,
                    filter_doc_hashes=request.paper_ids,
                )
                for chunk in retrieval.chunks:
                    key = (chunk.doc_hash, chunk.chunk_index)
                    if key not in seen_hashes:
                        seen_hashes.add(key)
                        all_chunks.append(chunk)
            except RuntimeError:
                # Vector store empty — skip retrieval
                logger.warning("Vector store empty — skipping retrieval.")
                break

        # Re-wrap merged chunks in a RetrievalResult for downstream agents
        from src.agents.retriever import RetrievalResult
        merged_retrieval = RetrievalResult(
            chunks=all_chunks[: settings.top_k_retrieval * 2],
            scores=[1.0] * len(all_chunks),
            query=request.question,
            total_candidates=len(all_chunks),
        )

        # ── Step 3: Synthesise ────────────────────────────────────────────
        synthesis = self._synthesiser.synthesise(
            request.question, merged_retrieval
        )

        # ── Step 4: Verify ────────────────────────────────────────────────
        verification = self._verifier.verify(synthesis)

        # ── Step 5: Cite ──────────────────────────────────────────────────
        from src.agents.citation import CitationStyle
        style = (
            CitationStyle.IEEE
            if request.citation_style.upper() == "IEEE"
            else CitationStyle.APA
        )
        self._citer._style = style
        citation_result = self._citer.generate_from_synthesis(synthesis)

        # ── Step 6: Report ────────────────────────────────────────────────
        report_md_path: Optional[str] = None
        report_pdf_path: Optional[str] = None

        if request.generate_report:
            report_result = self._reporter.generate(
                synthesis,
                citation_result,
                session_id=request.session_id,
                save_markdown=True,
                save_pdf=True,
            )
            if report_result.md_path:
                report_md_path = str(report_result.md_path)
            if report_result.pdf_path:
                report_pdf_path = str(report_result.pdf_path)

        # ── Step 7: Persist memory ────────────────────────────────────────
        from src.agents.memory import SessionRecord
        record = SessionRecord(
            session_id=request.session_id,
            question=request.question,
            answer=synthesis.answer,
            sub_questions=sub_questions,
            cited_sources=list({c.source for c in synthesis.cited_chunks}),
            citation_strings=[c.formatted for c in citation_result.citations],
            citation_style=request.citation_style,
            confidence_score=verification.overall_score,
            verdict=verification.verdict.value,
            model_id=synthesis.model_id,
            num_chunks=len(all_chunks),
            md_report_path=report_md_path,
            pdf_report_path=report_pdf_path,
        )
        try:
            self._memory.save_session(record)
        except Exception as exc:  # noqa: BLE001
            logger.warning("Memory save failed (non-fatal): %s", exc)

        # ── Assemble response ─────────────────────────────────────────────
        sources = [
            {
                "title": c.doc_title,
                "source": c.source,
                "page": c.page_number,
                "chunk_index": c.chunk_index,
            }
            for c in all_chunks
        ]

        response = ResearchResponse(
            answer=synthesis.answer,
            sub_questions=sub_questions,
            sources=sources,
            citations=[c.formatted for c in citation_result.citations],
            confidence=verification.overall_score,
            verdict=verification.verdict.value,
            report_md_path=report_md_path,
            report_pdf_path=report_pdf_path,
            session_id=request.session_id,
            metadata={
                "input_tokens": synthesis.input_tokens,
                "output_tokens": synthesis.output_tokens,
                "latency_s": synthesis.latency_s,
                "verification_checks": verification.check_scores,
                "planner_fallback": plan.used_fallback,
            },
        )

        logger.info(
            "[%s] Pipeline complete — verdict=%s score=%.2f",
            request.session_id[:8],
            verification.verdict.value,
            verification.overall_score,
        )
        return response
